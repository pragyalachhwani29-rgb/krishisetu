const dict = { en, hi, mr };

const C = createContext<{
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: string) => string;
}>({
  lang: 'en',
  setLang: () => {},
  t: (k) => en[k] || k,
});

export function I18nProvider({
  children,
}: {
  children: React.ReactNode;
}) {
  const [lang, setLang] = useState<Lang>(
    () => (localStorage.getItem('ks-language') as Lang) || 'en'
  );

  const change = (l: Lang) => {
    setLang(l);
    localStorage.setItem('ks-language', l);
  };

  const t = (k: string) => dict[lang][k] || en[k] || k;

  return (
    <C.Provider value={{ lang, setLang: change, t }}>
      {children}
    </C.Provider>
  );
}

export const useT = () => useContext(C);